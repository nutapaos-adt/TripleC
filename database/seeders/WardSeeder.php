<?php

namespace Database\Seeders;

use App\Models\Ward;
use Illuminate\Database\Seeder;

class WardSeeder extends Seeder
{
    /**
     * หน่วยงานที่ส่งเยี่ยมบ้านได้ — "หอผู้ป่วยอายุรกรรม" ยกเลิกใช้แล้ว (ฐานข้อมูลเดิมถูกปิดใช้งาน is_active=0 ไม่ลบ
     * เพราะอาจมีผู้ใช้/ใบส่งต่อเดิมอ้างอิงอยู่) — "แผนกส่งเสริมสุขภาพและเวชกรรมป้องกัน" คือหน่วยงานต้นสังกัดของ
     * ทีมเยี่ยมบ้าน (home_visit_team)
     */
    public function run(): void
    {
        foreach ([
            'หอผู้ป่วยชาย',
            'หอผู้ป่วยหนัก',
            'หอผู้ป่วยหญิง',
            'ห้องตรวจโรคผู้ป่วยนอก',
            'ห้องฉุกเฉิน',
            'แผนกส่งเสริมสุขภาพและเวชกรรมป้องกัน',
        ] as $name) {
            // ห้องฉุกเฉิน/ห้องตรวจโรคผู้ป่วยนอกไม่มีวันที่ Admit/จำหน่าย (ใช้ "วันที่พบผู้ป่วย" แทน)
            Ward::updateOrCreate(
                ['name' => $name],
                ['has_admission' => ! in_array($name, ['ห้องฉุกเฉิน', 'ห้องตรวจโรคผู้ป่วยนอก'], true)],
            );
        }
    }
}
